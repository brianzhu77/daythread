// Browser smoke for the editor and every screen over the converted v1 fixture (shot 1). Run:
//   cp tests/fixtures/v1/workspace.sqlite /tmp/smoke.sqlite
//   DAYTHREAD_STORAGE=sqlite DAYTHREAD_AUTH=off DAYTHREAD_SQLITE_PATH=/tmp/smoke.sqlite TZ=America/Vancouver npx vite preview --port 3043 &
//   TZ=America/Vancouver node scripts/browser-smoke.mjs /tmp/smoke-out      (screenshots land there)
// Needs a production build (npm run build) and Playwright's Chromium; set CHROMIUM to its path if not /opt/pw-browsers/chromium.
import assert from 'node:assert/strict'
import { chromium } from '@playwright/test'
const base = 'http://127.0.0.1:3043'
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM ?? '/opt/pw-browsers/chromium' })
const out = process.argv[2]
const results = []
async function run(name, width, fn) {
  const page = await browser.newPage({ viewport: { width, height: 900 } })
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  page.on('console', m => { if (m.type() === 'error') errors.push('console: ' + m.text()) })
  try { await fn(page); results.push({ name, ok: true, errors }) }
  catch (e) { results.push({ name, ok: false, error: e.message, errors }); await page.screenshot({ path: `${out}/fail-${name}.png`, fullPage: true }).catch(() => {}) }
  finally { await page.close() }
}
await run('today-desktop', 1280, async page => {
  await page.goto(base + '/')
  await page.locator('.editor-task-title').first().waitFor({ state: 'visible', timeout: 30000 })
  const text = await page.locator('main').innerText()
  assert(text.includes('Start the day'), 'morning card shown')
  assert(text.includes('Planned for Saturday'), 'the unfinished task from Oct 24 is offered')
  await page.screenshot({ path: `${out}/01-today-before.png`, fullPage: true })
  await page.getByRole('button', { name: 'Add Planned for Saturday to today' }).click()
  await page.getByText('Added to today').waitFor({ timeout: 10000 })
  await page.locator('.editor-task-title', { hasText: 'Planned for Saturday' }).waitFor({ timeout: 10000 })
  // Type a new to-do into the empty template row.
  const empty = page.locator('.editor-task-title').filter({ hasText: /^$/ }).first()
  await empty.click()
  await page.keyboard.type('Smoke to-do typed in the browser')
  await page.waitForFunction(() => document.querySelector('.editor-save-line')?.textContent === 'Saved', null, { timeout: 15000 })
  await page.screenshot({ path: `${out}/02-today-after.png`, fullPage: true })
  await page.reload()
  await page.locator('.editor-task-title', { hasText: 'Smoke to-do typed in the browser' }).waitFor({ timeout: 30000 })
  assert.equal(await page.locator('.editor-task-title', { hasText: 'Smoke to-do typed in the browser' }).count(), 1)
  assert.equal(await page.locator('.editor-task-title', { hasText: 'Planned for Saturday' }).count(), 1)
})
