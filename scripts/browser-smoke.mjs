await run('export', 1280, async page => {
  await page.goto(base + '/'); await page.locator('.editor-task-title').first().waitFor({ state: 'visible', timeout: 30000 })
  const res = await page.request.get(base + '/api/export')
  assert.equal(res.status(), 200)
  const cd = res.headers()['content-disposition'] ?? ''
  assert(/filename="daythread-.*\.zip"/.test(cd), 'zip download ' + cd)
  const body = await res.body()
  assert(body.length > 1000 && body[0] === 0x50 && body[1] === 0x4b, 'a zip')
  const { unzipSync, strFromU8 } = await import('fflate')
  const files = unzipSync(new Uint8Array(body))
  const names = Object.keys(files)
  assert(names.some(n => n.endsWith('workspace.json')), 'workspace.json in export: ' + names.join(','))
  const ws = JSON.parse(strFromU8(files[names.find(n => n.endsWith('workspace.json'))]))
  assert.equal(ws.schemaVersion, 2)
  assert(names.some(n => /korean|soup/i.test(n)), 'a markdown page named after its title: ' + names.join(','))
})
