// A4 screens on a built app (vite preview) over a copy of Brian's database: pages-trash-layout.md §6 states 1–9.
//   node tests/evidence/a4-trash/ui-check.mjs <base url> <screenshot dir> <playwright index.mjs>
const [base, out, pw] = process.argv.slice(2)
const { chromium } = await import(pw)
const page = 'fa95e8a3-dd0a-4b3c-8fcc-c1129c8c4820' // 韩国大酱汤, under Sun, Oct 18
const errors = []
const b = await chromium.launch()
const log = (ok, name, detail = '') => { console.log(`${ok ? 'ok  ' : 'FAIL'} ${name}${detail ? ` · ${detail}` : ''}`); if (!ok) process.exitCode = 1 }
async function open(width) {
  const p = await b.newPage({ viewport: { width, height: width < 600 ? 844 : 860 } })
  p.on('pageerror', e => errors.push(`${width}: ${e.message}`))
  p.on('console', m => { if (m.type() === 'error') errors.push(`${width}: ${m.text()}`) })
  return p
}
const toast = p => p.locator('[data-slot="toast"], .toast, [role="status"], [role="alert"]').filter({ hasText: /Moved to trash|Restored|Undone/ }).last()
const settle = p => p.waitForTimeout(700)

let p = await open(1280)
await p.goto(`${base}/tags`, { waitUntil: 'networkidle' })
const recipeBefore = await p.getByText('#recipe').first().locator('xpath=ancestor::*[self::a or self::li][1]').innerText().catch(() => '')
await p.goto(`${base}/pages?page=${page}`, { waitUntil: 'networkidle' }); await settle(p)
await p.getByRole('button', { name: 'Page actions' }).click()
await p.screenshot({ path: `${out}/1280-menu.png` })
await p.getByRole('menuitem', { name: 'Delete' }).click(); await settle(p)
log(/\/day\/2026-10-18/.test(p.url()), '1. lands on the parent day at the card', p.url())
log(await toast(p).innerText().then(t => /Moved to trash/.test(t)).catch(() => false), '1. notice "Moved to trash · Undo"')
const card = p.locator('.editor-page-card', { hasText: '韩国大酱汤' })
log(await card.locator('.in-trash-tag').isVisible(), '1. the card reads "In trash"')
await p.screenshot({ path: `${out}/1280-after-delete.png` })
log(await p.locator('.sidebar').getByText('Trash').isVisible(), '3. sidebar "Trash 1" row')
log(await p.locator('.sidebar .tree').getByText('佛卡夏披萨').isVisible() && !(await p.locator('.sidebar .tree').getByText('韩国大酱汤').count()), '1. the tree drops it (its sibling stays)')
await p.goto(`${base}/pages`, { waitUntil: 'networkidle' }); await settle(p)
log(!(await p.getByText('韩国大酱汤').count()), '8. "In your days" drops it')
await p.goto(`${base}/tags`, { waitUntil: 'networkidle' }); await settle(p)
const recipeAfter = await p.getByText('#recipe').first().locator('xpath=ancestor::*[self::a or self::li][1]').innerText().catch(() => '')
log(recipeBefore !== recipeAfter || !recipeAfter, '8. #recipe count changes', `${JSON.stringify(recipeBefore)} → ${JSON.stringify(recipeAfter)}`)
// 4. Open the trashed page from its card.
await p.goto(`${base}/day/2026-10-18`, { waitUntil: 'networkidle' }); await settle(p)
await p.locator('.editor-page-card', { hasText: '韩国大酱汤' }).click(); await settle(p)
log(await p.locator('.trash-banner').innerText().then(t => /In trash · was in Sun, Oct 18/.test(t)), '4. read-only with banner "In trash · was in Sun, Oct 18"')
log(!(await p.locator('.bn-editor').count()) && !(await p.getByRole('button', { name: 'Page actions' }).count()), '4. no editor, no ⋯')
await p.screenshot({ path: `${out}/1280-trashed-page.png` })
// 5. Trash screen and Restore.
await p.goto(`${base}/pages?view=trash`, { waitUntil: 'networkidle' }); await settle(p)
log(await p.locator('.trash-row').count() === 1, '3. Trash screen: one row')
log(await p.locator('.trash-row .card-row-detail').innerText().then(t => /^From Sun, Oct 18 · /.test(t)), '3. second line "From Sun, Oct 18 · {time}"')
await p.screenshot({ path: `${out}/1280-trash.png` })
await p.getByRole('button', { name: 'Restore' }).click(); await settle(p)
log(await p.getByText('Restored to Sun, Oct 18').isVisible() && await p.getByRole('button', { name: 'Open' }).isVisible(), '5. notice "Restored to Sun, Oct 18 · Open"')
log(await p.getByText('Trash is empty').isVisible(), '5. the row leaves')
await p.screenshot({ path: `${out}/1280-restored.png` })
await p.goto(`${base}/day/2026-10-18`, { waitUntil: 'networkidle' }); await settle(p)
log(!(await p.locator('.editor-page-card', { hasText: '韩国大酱汤' }).locator('.in-trash-tag').count()), '5. the card is normal again')
// 2. Delete from the sidebar tree, then Undo from the notice.
const expand = p.getByRole('button', { name: 'Expand Sun, Oct 18' })
if (await expand.count()) await expand.click()
const row = p.locator('.sidebar .tree-row', { hasText: '韩国大酱汤' })
await row.hover(); await row.getByRole('button', { name: /Actions for/ }).click()
await p.screenshot({ path: `${out}/1280-tree-menu.png` })
await p.getByRole('menuitem', { name: 'Delete' }).click(); await settle(p)
log(/\/day\/2026-10-18/.test(p.url()), '2. deleting a page that isn\'t open stays where you are', p.url())
await p.locator('button', { hasText: /^Undo$/ }).last().click(); await settle(p)
log(!(await p.locator('.in-trash-tag').count()) && await p.locator('.sidebar .tree').getByText('韩国大酱汤').isVisible(), '2. Undo: back, card normal, in the tree')
// 9. Day pages: no Delete.
await p.goto(`${base}/day/2026-10-18`, { waitUntil: 'networkidle' }); await settle(p)
log(!(await p.getByRole('button', { name: 'Page actions' }).count()), '9. a day page has no ⋯ / Delete')
await p.close()

// Phone: delete, then the Pages row, the Trash screen and the trashed page at 390.
p = await open(390)
await p.goto(`${base}/pages?page=${page}`, { waitUntil: 'networkidle' }); await settle(p)
await p.getByRole('button', { name: 'Page actions' }).click(); await p.getByRole('menuitem', { name: 'Delete' }).click(); await settle(p)
await p.screenshot({ path: `${out}/390-after-delete.png` })
await p.goto(`${base}/pages`, { waitUntil: 'networkidle' }); await settle(p)
log(await p.locator('.pages-trash-row').innerText().then(t => /Trash · 1/.test(t)), 'P1. Pages ends with "Trash · 1"')
await p.screenshot({ path: `${out}/390-pages.png`, fullPage: true })
await p.locator('.pages-trash-row').click(); await settle(p)
log(await p.locator('.trash-back').isVisible(), 'P2. "‹ Pages" back row')
const btn = await p.getByRole('button', { name: 'Restore' }).boundingBox()
log(btn && btn.height >= 44, 'P2. Restore is 44px tall', `${btn?.height}`)
await p.screenshot({ path: `${out}/390-trash.png` })
await p.locator('.trash-row .card-row').click(); await settle(p)
await p.screenshot({ path: `${out}/390-trashed-page.png` })
await p.getByRole('button', { name: 'Restore' }).click(); await settle(p)
log(await p.locator('.bn-editor').count() > 0, 'P3. Restore from the banner: the page becomes editable in place')
await p.close()
await b.close()
log(errors.length === 0, 'no page or console errors', errors.join(' | '))
