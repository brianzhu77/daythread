// A4 subpage states in the browser (pages-trash-layout §6 checks 1, 4, 6, 6b) on a copy seeded by nested-seed.ts.
//   node tests/evidence/a4-trash/nested-check.mjs <base url> <screenshot dir> <playwright index.mjs>
const [base, out, pw] = process.argv.slice(2)
const { chromium } = await import(pw)
const errors = []
const b = await chromium.launch()
const p = await b.newPage({ viewport: { width: 1280, height: 860 } })
p.on('pageerror', e => errors.push(e.message))
p.on('console', m => { if (m.type() === 'error') errors.push(m.text()) })
const log = (ok, name, detail = '') => { console.log(`${ok ? 'ok  ' : 'FAIL'} ${name}${detail ? ` · ${detail}` : ''}`); if (!ok) process.exitCode = 1 }
const settle = () => p.waitForTimeout(700)
const go = async path => { await p.goto(`${base}${path}`, { waitUntil: 'networkidle' }); await settle() }
const del = async () => { await p.getByRole('button', { name: 'Page actions' }).click(); await p.getByRole('menuitem', { name: 'Delete' }).click(); await settle() }
const visible = async text => p.getByText(text, { exact: true }).first().isVisible().catch(() => false)
const rows = () => p.locator('.trash-row').evaluateAll(els => els.map(e => e.innerText.replace(/\s+/g, ' ').trim()))

// 1. Delete a page with subpages: count, landing, tree and Subpages.
await go('/pages?page=kyoto')
await del()
log(/\/pages\?page=trip/.test(p.url()), '1. Kyoto (with Ryokan) → lands on Trip ideas', p.url())
log(await visible('Moved to trash · 1 subpage'), '1. notice "Moved to trash · 1 subpage"')
log(await p.locator('.editor-page-card', { hasText: 'Kyoto' }).locator('.in-trash-tag').isVisible(), '1. Kyoto card reads "In trash"')
log(!(await p.locator('.subpages').getByText('Kyoto').count()), '1. Subpages drops Kyoto')
await p.screenshot({ path: `${out}/n1-after-delete.png` })
// 2. Undo.
await p.locator('button', { hasText: /^Undo$/ }).last().click(); await settle()
log(await p.locator('.subpages').getByText('Kyoto').isVisible() && !(await p.locator('.in-trash-tag').count()), '2. Undo: Kyoto back in Subpages, card normal')
// 4. Delete the top page; open its trashed subpages.
await go('/pages?page=trip')
await del()
log(/\/pages$/.test(p.url()), '1. top-level Trip ideas → lands on Pages', p.url())
log(await visible('Moved to trash · 3 subpages'), '1. notice "Moved to trash · 3 subpages"')
await go('/pages?view=trash')
log(JSON.stringify(await rows()).includes('From Pages · with 3 subpages'), '3. one row "From Pages · with 3 subpages"', JSON.stringify(await rows()))
await p.locator('.trash-row .card-row').first().click(); await settle()
log(await p.locator('.trash-banner').innerText().then(t => /In trash · was in Pages/.test(t)), '4. Trip ideas banner "was in Pages"')
log(await p.locator('.subpages').getByText('Kyoto').isVisible() && await p.locator('.subpages').getByText('Packing').isVisible(), '4. its Subpages list Kyoto and Packing')
await p.screenshot({ path: `${out}/n4-trashed-top.png` })
await p.locator('.subpages').getByText('Kyoto').click(); await settle()
log(await p.locator('.trash-banner').innerText().then(t => /In trash · deleted with Trip ideas/.test(t)), '4. Kyoto banner "deleted with Trip ideas"')
log(await p.locator('.subpages').getByText('Ryokan shortlist').isVisible(), '4. Kyoto still lists Ryokan')
await p.screenshot({ path: `${out}/n4-trashed-child.png` })
// 6b. Restore only Kyoto from its banner → top level with its own subtree; move it; then restore the rest.
await p.getByRole('button', { name: 'Restore' }).click(); await settle()
log(await visible('Restored Kyoto to Pages · Trip ideas is in trash'), '6b. notice "Restored Kyoto to Pages · Trip ideas is in trash"')
log(await p.locator('.bn-editor').count() > 0 && await p.locator('.subpages').getByText('Ryokan shortlist').isVisible(), '6b. Kyoto editable in place, Ryokan back under it')
await p.screenshot({ path: `${out}/n6b-restored-child.png` })
await go('/pages?view=trash')
log(JSON.stringify(await rows()).includes('with 1 subpage'), '6b. Trip ideas row now "with 1 subpage"', JSON.stringify(await rows()))
await go('/pages?page=kyoto')
await p.getByRole('button', { name: 'Page actions' }).click(); await p.getByRole('menuitem', { name: 'Move to…' }).click(); await settle()
await p.keyboard.type('Oct 18'); await settle()
await p.getByRole('option', { name: /Sun, Oct 18/ }).first().click(); await settle()
await go('/pages?view=trash')
await p.getByRole('button', { name: 'Restore' }).click(); await settle()
log(await visible('Restored to Pages'), '6b. Restore the row: "Restored to Pages"')
await go('/pages?page=trip')
const sub = await p.locator('.subpages').innerText().catch(() => '')
log(/Packing/.test(sub) && !/Kyoto/.test(sub), '6b. Trip ideas back with Packing; Kyoto stays where it was moved (Sun, Oct 18)', sub.replace(/\s+/g, ' '))
await go('/pages?page=kyoto')
log(await p.locator('.crumbs').innerText().then(t => /Sun, Oct 18/.test(t)), '6b. Kyoto is still under Sun, Oct 18', await p.locator('.crumbs').innerText())
// 6. Delete a child, then its parent, separately; restore the child alone.
await go('/pages?page=packing'); await del()
await go('/pages?page=trip'); await del()
await go('/pages?view=trash')
const two = await rows()
log(two.length === 2 && two.some(r => r.startsWith('Packing') && r.includes('From Trip ideas')) && two.some(r => r.startsWith('Trip ideas')), '6. two rows, Packing "From Trip ideas"', JSON.stringify(two))
await p.locator('.trash-row', { hasText: 'Packing' }).getByRole('button', { name: 'Restore' }).click(); await settle()
log(await visible('Restored Packing to Pages · Trip ideas is in trash'), '6. notice "Restored Packing to Pages · Trip ideas is in trash"')
await p.screenshot({ path: `${out}/n6-restored-alone.png` })
await go('/pages')
log(await p.locator('.card-list').first().getByText('Packing').isVisible(), '6. Packing at top level in Pages')
await b.close()
log(errors.length === 0, 'no page or console errors', errors.join(' | '))
