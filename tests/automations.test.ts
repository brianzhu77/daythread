// Automations (docs/design/automations.md, G3-13 to G3-17): rules run inside the command that set them off, each on its own copy, with one Undo.
import { test } from 'node:test'
import assert from 'node:assert/strict'
import { stepsKey, writeSteps, type ButtonStep } from '../src/domain/buttons.ts'
import type { Automation } from '../src/domain/automations.ts'
import { pageContentKey } from '../src/domain/editor-document.ts'
import { commandSchema } from '../src/domain/command-schema.ts'
import { harness } from './v2-helpers.ts'

const at = '2026-11-05T10:00:00.000Z', today = '2026-11-05'
const setN = (raw: number, id = 'n', name = 'N'): ButtonStep => ({ id: `s-${id}`, kind: 'edit-property', set: [{ id, name, type: id === 'n' ? 'number' : 'text', value: { kind: 'fixed', raw } }] } as ButtonStep)
const rule = (over: Partial<Automation> = {}): Automation => ({ id: 'r', name: 'Log finish', active: true, triggers: [{ kind: 'property-edited', propertyId: 'st', name: 'Status', condition: { by: 'st', op: 'isAnyOf', value: ['done'] } }], steps: writeSteps([setN(5)]), ...over })
function setup(rules: Automation[] = []) {
  const h = harness()
  const C = (change: unknown, pageId = 'runs') => h.run({ type: 'change-database', pageId, change } as never)
  h.run({ type: 'create-database', pageId: 'runs', homeBlockId: null, title: 'Runs' })
  C({ kind: 'addProperty', property: { id: 'n', name: 'N', type: 'number' } })
  C({ kind: 'addProperty', property: { id: 'st', name: 'Status', type: 'select', options: [{ id: 'todo', name: 'Todo', color: 'gray' }, { id: 'done', name: 'Done', color: 'gray' }] } })
  h.run({ type: 'add-row', databaseId: 'runs', pageId: 'r1', title: 'One', values: { n: 1, st: 'todo' }, at } as never)
  h.run({ type: 'add-row', databaseId: 'runs', pageId: 'r2', title: 'Two', values: { n: 2, st: 'todo' }, at } as never)
  for (const r of rules) C({ kind: 'addAutomation', automation: r })
  return { h, C }
}
const edit = (h: ReturnType<typeof harness>, id: string, values: object, expected: object) => h.run({ type: 'set-values', pageId: id, values, expected, at } as never)
const val = (h: ReturnType<typeof harness>, id: string, key = 'n') => h.page(id).values?.[key]
const rules = (h: ReturnType<typeof harness>) => h.page('runs').database!.automations ?? []

test('a rule runs inside his edit, with one Undo over both, and the receipt says what ran', () => {
  const { h } = setup([rule()])
  const { receipt } = edit(h, 'r1', { st: 'done' }, { st: 'todo' })
  assert.equal(val(h, 'r1'), 5)
  assert.deepEqual(receipt.automations, { databaseId: 'runs', ran: ['Log finish'], paused: [] })
  assert.ok(rules(h)[0]!.lastRanAt)
  h.run({ type: 'undo', targetOperationId: receipt.operationId })
  assert.equal(val(h, 'r1'), 1)
  assert.equal(val(h, 'r1', 'st'), 'todo')
  assert.equal(rules(h)[0]!.lastRanAt, undefined)
})
test('only a value change that holds sets it off: other values, a body, and a condition that isn\'t met don\'t', () => {
  const { h } = setup([rule()])
  edit(h, 'r1', { n: 9 }, { n: 1 })
  assert.equal(val(h, 'r1'), 9)
  h.save('r1', () => [{ id: 'b', type: 'paragraph', props: {}, content: [{ type: 'text', text: 'Body', styles: {} }], children: [] }])
  assert.equal(rules(h)[0]!.lastRanAt, undefined)
  const { receipt } = edit(h, 'r2', { st: 'todo' }, { st: 'todo' })
  assert.equal(receipt.automations, undefined)
})
test('all: every condition true after this edit and one of them just changed, so an unrelated edit doesn\'t repeat it; any: one is enough', () => {
  const both: Automation = rule({ triggers: [{ kind: 'property-edited', propertyId: 'st', name: 'Status', condition: { by: 'st', op: 'isAnyOf', value: ['done'] } }, { kind: 'property-edited', propertyId: 'n', name: 'N', condition: { by: 'n', op: 'gt', value: 5 } as never }], steps: writeSteps([{ id: 'e', kind: 'edit-property', set: [{ id: 'mark', name: 'Mark', value: { kind: 'fixed', raw: 'x' } }] }]) })
  const { h, C } = setup()
  C({ kind: 'addProperty', property: { id: 'mark', name: 'Mark', type: 'text' } })
  C({ kind: 'addProperty', property: { id: 'other', name: 'Other', type: 'text' } })
  C({ kind: 'addAutomation', automation: both })
  edit(h, 'r1', { st: 'done' }, { st: 'todo' })
  assert.equal(val(h, 'r1', 'mark'), undefined, 'one of two isn\'t all')
  edit(h, 'r1', { n: 9 }, { n: 1 })
  assert.equal(val(h, 'r1', 'mark'), 'x', 'now both hold, and one just changed')
  const ran = rules(h)[0]!.lastRanAt
  edit(h, 'r1', { other: 'y' }, {})
  assert.equal(rules(h)[0]!.lastRanAt, ran, 'an unrelated edit doesn\'t repeat it')
})
test('Row added: by + New and a Duplicate and a button; not by Undo, restore or CSV', () => {
  const added = rule({ triggers: [{ kind: 'row-added' }] })
  const { h } = setup([added])
  h.run({ type: 'add-row', databaseId: 'runs', pageId: 'r3', title: 'Three', values: { n: 1 }, at } as never)
  assert.equal(val(h, 'r3'), 5)
  h.run({ type: 'add-row', databaseId: 'runs', pageId: 'r4', title: '', copyOf: 'r1', at } as never)
  assert.equal(val(h, 'r4'), 5)
  const gone = h.run({ type: 'delete-page', pageId: 'r3', at })
  h.run({ type: 'undo', targetOperationId: gone.receipt.operationId })
  assert.equal(rules(h).length, 1)
  h.run({ type: 'delete-page', pageId: 'r2', at })
  h.run({ type: 'restore-page', pageId: 'r2' })
  assert.equal(val(h, 'r2'), 2, 'a restore isn\'t a new row')
  h.run({ type: 'add-rows', databaseId: 'runs', rows: [{ pageId: 'imp', title: 'Imported', values: { n: 1 } }], at } as never)
  assert.equal(val(h, 'imp'), 1, 'nor is an import')
})
test('no chains: a rule setting what it watches runs once, a rule\'s writes fire nothing, and a button fires one once', () => {
  const self = rule({ id: 'self', name: 'Self', triggers: [{ kind: 'property-edited', propertyId: 'n', name: 'N' }], steps: writeSteps([setN(100)]) })
  const watcher = rule({ id: 'w', name: 'Watcher', triggers: [{ kind: 'property-edited', propertyId: 'st', name: 'Status' }], steps: writeSteps([setN(7)]) })
  const { h, C } = setup([self])
  const { receipt } = edit(h, 'r1', { n: 3 }, { n: 1 })
  assert.equal(val(h, 'r1'), 100)
  assert.deepEqual(receipt.automations?.ran, ['Self'])
  C({ kind: 'removeAutomation', automationId: 'self' })
  C({ kind: 'addAutomation', automation: watcher })
  const steps = writeSteps([{ id: 'e', kind: 'edit-rows', databaseId: 'runs', databaseName: 'Runs', filter: [], set: [{ id: 'st', name: 'Status', value: { kind: 'fixed', raw: 'done' } }] }])
  h.run({ type: 'create-document', title: 'P', body: '', pageId: 'p' })
  h.save('p', () => [{ id: 'btn', type: 'button', props: { label: 'Go', steps }, children: [] }])
  const tap = h.run({ type: 'run-button', pageId: 'p', blockId: 'btn', stepsKey: stepsKey(steps), expectedContent: pageContentKey(h.page('p')), at, today })
  assert.deepEqual(tap.receipt.automations?.ran, ['Watcher'])
  assert.equal(val(h, 'r2'), 7, 'a button\'s change fires the rule')
})
test('a retry doesn\'t evaluate rules again', () => {
  const { h } = setup([rule({ triggers: [{ kind: 'row-added' }], steps: writeSteps([{ id: 'a', kind: 'add-row', databaseId: 'runs', databaseName: 'Runs', title: 'Made', set: [] }]) })])
  const action = { type: 'add-row', databaseId: 'runs', pageId: 'r9', title: 'Nine', values: {}, at } as never
  const first = h.run(action, 'tap'), n = h.ws.pages.length, second = h.run(action, 'tap')
  assert.deepEqual(second.receipt.automations, first.receipt.automations)
  assert.equal(h.ws.pages.length, n)
})
test('a rule that fails: his edit stands, its steps are dropped whole, it pauses and says why; a later rule still runs', () => {
  const bad = rule({ id: 'bad', name: 'Bad', steps: writeSteps([setN(5), { id: 'x', kind: 'edit-property', set: [{ id: 'n', name: 'N', value: { kind: 'fixed', raw: 'words' } }] }]) })
  const good = rule({ id: 'good', name: 'Good', steps: writeSteps([{ id: 'e', kind: 'add-row', databaseId: 'runs', databaseName: 'Runs', title: 'Logged', set: [] }]) })
  const { h } = setup([bad, good])
  const { receipt } = edit(h, 'r1', { st: 'done' }, { st: 'todo' })
  assert.equal(val(h, 'r1', 'st'), 'done', 'his edit is kept')
  assert.equal(val(h, 'r1'), 1, 'the first step of the failed rule is gone too')
  assert.equal(rules(h)[0]!.active, false)
  assert.match(rules(h)[0]!.paused!.reason, /Set N: Not a value for N/)
  assert.deepEqual(receipt.automations?.ran, ['Good'])
  assert.equal(receipt.automations?.paused[0]?.name, 'Bad')
  assert.ok(h.ws.pages.some(p => p.title === 'Logged'))
  h.run({ type: 'undo', targetOperationId: receipt.operationId })
  assert.equal(rules(h)[0]!.active, true, 'Undo brings back the pause too')
  assert.equal(val(h, 'r1', 'st'), 'todo')
})
test('a delete or a change of type pauses at the next edit, and a fix turns it back on; off by hand stays off', () => {
  const { h, C } = setup()
  C({ kind: 'addProperty', property: { id: 'tx', name: 'Tx', type: 'text' } })
  C({ kind: 'addAutomation', automation: rule({ steps: writeSteps([setN(5), { id: 't', kind: 'edit-property', set: [{ id: 'tx', name: 'Tx', type: 'text', value: { kind: 'fixed', raw: 'x' } }] }]) }) })
  C({ kind: 'removeProperty', propertyId: 'tx' })
  const { receipt } = edit(h, 'r1', { st: 'done' }, { st: 'todo' })
  assert.deepEqual(receipt.automations?.paused, [{ name: 'Log finish', reason: 'Tx was deleted' }])
  assert.equal(val(h, 'r1'), 1)
  C({ kind: 'updateAutomation', automation: { ...rules(h)[0]!, steps: writeSteps([setN(5)]) } })
  assert.equal(rules(h)[0]!.active, true, 'the fix turns it back on')
  assert.equal(rules(h)[0]!.paused, undefined)
  C({ kind: 'setAutomationActive', automationId: 'r', active: false })
  C({ kind: 'updateAutomation', automation: { ...rules(h)[0]!, name: 'Renamed' } })
  assert.equal(rules(h)[0]!.active, false, 'off by hand stays off')
  edit(h, 'r2', { st: 'done' }, { st: 'todo' })
  assert.equal(val(h, 'r2'), 2)
})
test('the limit is the command\'s: earlier rules stay, the rest pause with its words, and rules not set off stay on', () => {
  const first = rule({ id: 'first', name: 'First', steps: writeSteps([setN(5)]) })
  const every = (id: string): ButtonStep => ({ id, kind: 'edit-rows', databaseId: 'runs', databaseName: 'Runs', filter: [], set: [{ id: 'n', name: 'N', value: { kind: 'fixed', raw: 8 } }] })
  const eats = rule({ id: 'eats', name: 'Eats', steps: writeSteps([every('e1'), every('e2')]) })
  const third = rule({ id: 'third', name: 'Third', steps: writeSteps([setN(6)]) })
  const other = rule({ id: 'other', name: 'Other', triggers: [{ kind: 'row-added' }] })
  const { h } = setup([first, eats, third, other])
  // Twice over more than half the allowance, so it's the second step that goes past it.
  h.run({ type: 'add-rows', databaseId: 'runs', rows: Array.from({ length: 5_100 }, (_, i) => ({ pageId: `x${i}`, title: `x${i}`, values: {} })), at } as never)
  const { receipt } = edit(h, 'r1', { st: 'done' }, { st: 'todo' })
  assert.deepEqual(receipt.automations?.ran, ['First'])
  assert.deepEqual(receipt.automations?.paused.map(p => [p.name, p.reason]), [['Eats', 'Not run · command limit reached'], ['Third', 'Not run · command limit reached']])
  assert.equal(val(h, 'r1', 'st'), 'done')
  assert.equal(val(h, 'r1'), 5, 'the earlier rule stayed')
  assert.equal(rules(h).find(r => r.id === 'other')!.active, true, 'one not set off stays on')
})
test('In a view: only rows it shows; rename keeps it working; rules reorder, run in order, and the schema accepts them', () => {
  const { h, C } = setup()
  const view = h.page('runs').database!.views[0]!
  C({ kind: 'addView', view: { ...view, id: 'big', name: 'Big', filter: [{ by: 'n', op: 'gt', value: 1 }] } })
  C({ kind: 'addAutomation', automation: rule({ id: 'a', name: 'A', viewId: 'big', steps: writeSteps([setN(50)]) }) })
  edit(h, 'r1', { st: 'done' }, { st: 'todo' })
  assert.equal(val(h, 'r1'), 1, 'not in the view')
  edit(h, 'r2', { st: 'done' }, { st: 'todo' })
  assert.equal(val(h, 'r2'), 50)
  C({ kind: 'updateProperty', propertyId: 'n', name: 'Number' })
  edit(h, 'r2', { st: 'todo' }, { st: 'done' })
  C({ kind: 'addAutomation', automation: rule({ id: 'b', name: 'B', steps: writeSteps([setN(60)]) }) })
  C({ kind: 'moveAutomation', automationId: 'b', beforeId: 'a' })
  assert.deepEqual(rules(h).map(r => r.id), ['b', 'a'])
  edit(h, 'r2', { st: 'done' }, { st: 'todo' })
  assert.equal(val(h, 'r2'), 50, 'in list order, so a runs last')
  assert.equal(commandSchema.safeParse({ operationId: 'o', expectedRevision: 0, action: { type: 'change-database', pageId: 'runs', change: { kind: 'addAutomation', automation: rule() } } }).success, true)
})
